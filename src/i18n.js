const supported = l => LANGS.some(([k]) => k === l);
function initialLang() {
  try { const s = localStorage.getItem(LS_KEY); if (supported(s)) return s; } catch (e) { /* storage unavailable */ }
  const nav = (typeof navigator !== "undefined" && (navigator.languages || [navigator.language])) || [];
  for (const n of nav) { const k = String(n || "").toLowerCase().slice(0, 2); if (k === "ru" || k === "uk") return k; }
  return "en";
}
let lang = initialLang();
const listeners = new Set();
export const getLang = () => lang;
export function setLang(l) {
  if (!supported(l) || l === lang) return;
  lang = l;
  try { localStorage.setItem(LS_KEY, l); } catch (e) { /* storage unavailable */ }
  if (typeof document !== "undefined") document.documentElement.lang = l;
  for (const fn of listeners) fn(l);
}
export const onLangChange = fn => { listeners.add(fn); return () => listeners.delete(fn); };
if (typeof document !== "undefined") document.documentElement.lang = lang;

// ---------------------------------------------------------------- lookup
const fill = (s, args) => s.replace(/\{(\d+)\}/g, (m, k) => (args[k] !== undefined ? String(args[k]) : m));
function pluralIndex(n) {
  n = Math.abs(n);
  if (lang === "en") return n === 1 ? 0 : 1;
  const d = n % 10, h = n % 100;
  if (d === 1 && h !== 11) return 0;
  if (d >= 2 && d <= 4 && (h < 12 || h > 14)) return 1;
  return 2;
}
const raw = key => { const v = TABLES[lang][key]; return v !== undefined ? v : TABLES.en[key]; };
export const has = key => TABLES[lang][key] !== undefined || TABLES.en[key] !== undefined;
// t(key, ...args): {0}, {1} … are replaced by args. Plural entries take the count as the first argument.
export function t(key, ...args) {
  let v = raw(key);
  if (v === undefined) return key;
  if (Array.isArray(v)) v = v[Math.min(v.length - 1, pluralIndex(+args[0] || 0))];
  return fill(v, args);
}
// tOr(key, fallback, ...args): like t(), with a fallback for keys that have no English entry (node titles, items …)
export const tOr = (key, fallback, ...args) => (has(key) ? t(key, ...args) : fallback);
export const builtinDoc = (call, en) => (DOCS[lang] && DOCS[lang][call]) || en;
